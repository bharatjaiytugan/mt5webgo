// MTCryptAES implements AES-256 block encryption with custom key expansion.
type MTCryptAES struct {
	nk          int      // number of 32-bit words in the key
	nr          int      // number of rounds
	cipher      []int32  // expanded key schedule
	cipherTable [4][mNb]byte // state matrix
}

// NewMTCryptAES creates a new MTCryptAES with the given key.
func NewMTCryptAES(key []byte) *MTCryptAES {
	a := &MTCryptAES{}
	a.Init(key)
	return a
}

// Init initializes (or re-initializes) the AES cipher with the given key.
func (a *MTCryptAES) Init(key []byte) {
	if key == nil || len(key) == 0 {
		return
	}
	a.nk = len(key) / 4
	a.nr = a.nk + mNb + 2
	if a.nk != 4 && a.nk != 6 && a.nk != 8 {
		logWrite(LogTypeError, fmt.Sprintf("Key is %d bits long. *not* 128, 192, or 256.", a.nk*32))
		return
	}
	a.keyExpansion(key)
}

// keyExpansion expands the cipher key into the key schedule.
func (a *MTCryptAES) keyExpansion(key []byte) {
	a.cipher = make([]int32, mNb*(a.nr+1))
	i := 0
	for ; i < a.nk; i++ {
		a.cipher[i] = int32(key[4*i])
		a.cipher[i] <<= 8
		a.cipher[i] += int32(key[4*i+1])
		a.cipher[i] <<= 8
		a.cipher[i] += int32(key[4*i+2])
		a.cipher[i] <<= 8
		a.cipher[i] += int32(key[4*i+3])
	}
	for ; i < mNb*(a.nr+1); i++ {
		temp := a.cipher[i-1]
		if i%a.nk == 0 {
			temp = int32(uint32(SubWord(RotWord(temp))) ^ rcon[i/a.nk])
		} else if a.nk > 6 && i%a.nk == 4 {
			temp = SubWord(temp)
		}
		a.cipher[i] = int32(uint32(a.cipher[i-a.nk]^temp) & 0xFFFFFFFF)
	}
}

// RotWord applies a cyclic permutation to a 4-byte word.
func RotWord(w int32) int32 {
	temp := w >> 24
	w <<= 8
	w = int32(uint32(w) & 0xFFFFFFFF)
	if temp < 0 {
		temp = 256 + temp
	}
	w += temp
	return w
}

// SubWord applies S-box substitution to each byte of a 4-byte word.
func SubWord(w int32) int32 {
	for i := 0; i < 4; i++ {
		temp := w >> 24
		if temp < 0 {
			temp = 256 + temp
		}
		w <<= 8
		w = int32(uint32(w) & 0xFFFFFFFF)
		w += int32(sbox[temp])
	}
	return w
}

// addRoundKey adds the key schedule for a round to the state matrix.
func (a *MTCryptAES) addRoundKey(round int) {
	for i := 0; i < 4; i++ {
		for j := 0; j < mNb; j++ {
			temp := a.cipher[round*mNb+j] >> int32((3-i)*8)
			temp %= 256
			if temp < 0 {
				temp = 256 + temp
			}
			a.cipherTable[i][j] ^= byte(temp)
		}
	}
}

// mixColumns mixes each column of the state matrix.
func (a *MTCryptAES) mixColumns() {
	for i := 0; i < mNb; i++ {
		s0 := a.cipherTable[0][i]
		s1 := a.cipherTable[1][i]
		s2 := a.cipherTable[2][i]
		s3 := a.cipherTable[3][i]
		a.cipherTable[0][i] = Mult(0x02, s0) ^ Mult(0x03, s1) ^ Mult(0x01, s2) ^ Mult(0x01, s3)
		a.cipherTable[1][i] = Mult(0x01, s0) ^ Mult(0x02, s1) ^ Mult(0x03, s2) ^ Mult(0x01, s3)
		a.cipherTable[2][i] = Mult(0x01, s0) ^ Mult(0x01, s1) ^ Mult(0x02, s2) ^ Mult(0x03, s3)
		a.cipherTable[3][i] = Mult(0x03, s0) ^ Mult(0x01, s1) ^ Mult(0x01, s2) ^ Mult(0x02, s3)
	}
}

// shiftRows applies a cyclic shift to the last 3 rows of the state matrix.
func (a *MTCryptAES) shiftRows() {
	var temp [4]byte
	for i := 1; i < 4; i++ {
		for j := 0; j < mNb; j++ {
			temp[j] = a.cipherTable[i][(j+i)%mNb]
		}
		for j := 0; j < mNb; j++ {
			a.cipherTable[i][j] = temp[j]
		}
	}
}

// subBytes applies S-Box substitution to each byte of the state matrix.
func (a *MTCryptAES) subBytes() {
	for i := 0; i < 4; i++ {
		for j := 0; j < mNb; j++ {
			a.cipherTable[i][j] = sbox[a.cipherTable[i][j]]
		}
	}
}

// Mult multiplies two polynomials in GF(2^8) modulo x^8+x^4+x^3+x+1.
func Mult(a, b byte) byte {
	sum := int(ltable[a]) + int(ltable[b])
	sum %= 255
	sum = int(atable[sum])
	if a == 0 {
		return 0
	}
	if b == 0 {
		return 0
	}
	return byte(sum)
}

// EncryptBlock encrypts a single 16-byte block.
func (a *MTCryptAES) EncryptBlock(x []byte) []byte {
	a.cipherTable = [4][mNb]byte{}
	y := make([]byte, len(x))
	// place input into state matrix in column order
	for i := 0; i < 4*mNb; i++ {
		a.cipherTable[i%4][(i-i%mNb)/mNb] = x[i]
	}
	a.addRoundKey(0)
	for i := 1; i < a.nr; i++ {
		a.subBytes()
		a.shiftRows()
		a.mixColumns()
		a.addRoundKey(i)
	}
	a.subBytes()
	a.shiftRows()
	a.addRoundKey(a.nr)
	// extract state matrix into output in column order
	for i := 0; i < 4*mNb; i++ {
		y[i] = a.cipherTable[i%4][(i-i%mNb)/mNb]
	}
	return y
}
